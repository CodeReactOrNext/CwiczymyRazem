import { createHash } from 'crypto';
import { build } from 'esbuild';
import { promises as fs } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

/**
 * Bundles the guitar DSP (aubio + the shared processor) for the desktop shell,
 * which runs it next to the native capture instead of in the window
 * (electron/captureDspHost.js).
 *
 * Entry: src/hooks/guitarDspEngine.ts. Three files come out:
 *  - electron/generated/guitarDspEngine.js      the bundle the shell ships
 *  - electron/generated/guitarDspEngineHash.js  its hash, for the shell
 *  - src/hooks/generated/guitarDspEngineHash.ts the same hash, for the web app
 *
 * The shell runs the bundle only for a web app built with the same hash, so a
 * change to the detectors reaches desktop players with the web deploy (their
 * window runs the new ones itself) and moves into the shell with its next
 * release.
 *
 * Run after changing the detectors: `node scripts/buildGuitarDspEngine.mjs`.
 * guitarDspEngineBundle.test.ts fails while the committed files are out of date.
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ENTRY = join(ROOT, 'src/hooks/guitarDspEngine.ts');
export const BUNDLE_PATH = join(ROOT, 'electron/generated/guitarDspEngine.js');
export const SHELL_HASH_PATH = join(ROOT, 'electron/generated/guitarDspEngineHash.js');
export const WEB_HASH_PATH = join(ROOT, 'src/hooks/generated/guitarDspEngineHash.ts');

const HEADER = '// Generated by scripts/buildGuitarDspEngine.mjs from src/hooks/guitarDspEngine.ts — do not edit.\n';

/** The three files' contents, by path. */
export async function buildGuitarDspEngine() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'cjs',
    platform: 'node',
    minify: true,
    legalComments: 'none',
    target: 'node20',
    tsconfig: join(ROOT, 'tsconfig.json'),
    logLevel: 'silent',
  });
  const bundle = HEADER + result.outputFiles[0].text.trim() + '\n';
  const hash = createHash('sha256').update(bundle).digest('hex').slice(0, 16);
  return {
    [BUNDLE_PATH]: bundle,
    [SHELL_HASH_PATH]: `${HEADER}module.exports = ${JSON.stringify(hash)};\n`,
    [WEB_HASH_PATH]: `${HEADER}export const GUITAR_DSP_ENGINE_HASH = ${JSON.stringify(hash)};\n`,
  };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const files = await buildGuitarDspEngine();
  for (const [path, source] of Object.entries(files)) {
    await fs.mkdir(dirname(path), { recursive: true });
    await fs.writeFile(path, source);
  }
  console.log(`buildGuitarDspEngine: ${(files[BUNDLE_PATH].length / 1024).toFixed(1)} KB → ${BUNDLE_PATH}`);
}
