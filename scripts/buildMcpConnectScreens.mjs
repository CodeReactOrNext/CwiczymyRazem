/**
 * Turns the raw screenshots for Settings → AI assistants → "How to connect"
 * into the WebP files the guide shows, and writes the manifest it reads.
 *
 *   node scripts/buildMcpConnectScreens.mjs <folder with PNG/JPG screenshots>
 *
 * A file named after a step (see SCREENS below, e.g. `claude-1.png`) becomes
 * `public/images/mcp-connect/claude-1.webp`, at most 1200 px wide. Other files
 * are ignored. Steps without a screenshot keep their drawn stand-in, so the
 * guide works with any subset. Re-run after replacing a shot.
 *
 * Optional `<name>.json` next to a screenshot crops and redacts it first:
 *   { "crop": { "left": 0, "top": 0, "width": 1600, "height": 900 },
 *     "blur": [{ "left": 10, "top": 20, "width": 300, "height": 40 }] }
 * (coordinates in the original image's pixels; blur boxes are applied before
 * the crop). Use it for anything personal — e-mail, chat titles, avatars.
 */
import fs from "node:fs";
import path from "node:path";

import sharp from "sharp";

const SCREENS = [
  "claude-1",
  "claude-2",
  "claude-4",
  "chatgpt-1",
  "chatgpt-2",
  "chatgpt-3",
  "cursor-2",
  "consent",
];
const MAX_WIDTH = 1200;
const OUT_DIR = "public/images/mcp-connect";
const MANIFEST = "src/feature/settings/data/mcpConnectScreens.ts";

const source = process.argv[2];
if (!source || !fs.existsSync(source)) {
  console.error("Usage: node scripts/buildMcpConnectScreens.mjs <folder>");
  process.exit(1);
}
fs.mkdirSync(OUT_DIR, { recursive: true });

const findSource = (name) =>
  ["png", "jpg", "jpeg", "webp"]
    .map((ext) => path.join(source, `${name}.${ext}`))
    .find((file) => fs.existsSync(file));

const blurBox = async (image, box) => {
  const region = await image
    .clone()
    .extract(box)
    .blur(Math.max(8, Math.round(Math.min(box.width, box.height) / 3)))
    .toBuffer();
  return { input: region, left: box.left, top: box.top };
};

const manifest = {};
for (const name of SCREENS) {
  const file = findSource(name);
  const out = path.join(OUT_DIR, `${name}.webp`);
  if (!file) {
    // A shot that was removed from the source keeps its old WebP, so the
    // manifest has to keep listing it.
    if (fs.existsSync(out)) {
      const { width, height } = await sharp(out).metadata();
      manifest[name] = { width, height };
    }
    continue;
  }

  const optionsFile = path.join(source, `${name}.json`);
  const options = fs.existsSync(optionsFile)
    ? JSON.parse(fs.readFileSync(optionsFile, "utf8"))
    : {};

  let image = sharp(file);
  if (options.blur?.length) {
    const overlays = await Promise.all(
      options.blur.map((box) => blurBox(sharp(file), box)),
    );
    image = sharp(await image.composite(overlays).png().toBuffer());
  }
  if (options.crop) image = image.extract(options.crop);

  const buffer = await image
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toBuffer();
  fs.writeFileSync(out, buffer);
  const { width, height } = await sharp(buffer).metadata();
  manifest[name] = { width, height };
  console.log(
    `${name}: ${width}×${height}, ${Math.round(buffer.length / 1024)} KB`,
  );
}

const entries = Object.entries(manifest)
  .map(
    ([name, { width, height }]) =>
      `  "${name}": { width: ${width}, height: ${height} },`,
  )
  .join("\n");
fs.writeFileSync(
  MANIFEST,
  `// Generated by scripts/buildMcpConnectScreens.mjs — do not edit by hand.

/** The "How to connect" steps that have a real screenshot, and its size. */
export const MCP_CONNECT_SCREENS: Record<
  string,
  { width: number; height: number } | undefined
> = {
${entries}
};
`,
);
console.log(
  `${Object.keys(manifest).length} of ${SCREENS.length} steps have a screenshot.`,
);
