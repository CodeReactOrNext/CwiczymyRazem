import { build } from 'esbuild';
import { promises as fs } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath, pathToFileURL } from 'url';

/**
 * Bundles the practice session's tab board for the MCP tab preview
 * (`riffquest_preview_tab`), which runs in the chat client's sandbox and can't
 * load anything from riff.quest.
 *
 * Entry: src/lib/mcp/apps/tabBoard/tabBoard.ts — the session's
 * TablatureViewer.worker plus a little driver around it. The worker module runs
 * on the page's thread, so every `self` in it is pointed at the stand-in from
 * boardSelf.ts. The result is one script, inlined into the preview's HTML.
 *
 * Run after changing the board or the worker: `node scripts/buildMcpTabBoard.mjs`.
 * tabBoardBundle.test.ts fails while the committed bundle is out of date.
 */

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const ENTRY = join(ROOT, 'src/lib/mcp/apps/tabBoard/tabBoard.ts');
export const OUTPUT_PATH = join(ROOT, 'src/lib/mcp/apps/generated/tabBoardBundle.ts');

export async function bundleTabBoard() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    write: false,
    format: 'iife',
    minify: true,
    legalComments: 'none',
    target: 'es2020',
    tsconfig: join(ROOT, 'tsconfig.json'),
    define: { self: '__tabBoardSelf' },
    logLevel: 'silent',
  });
  // Inlined into a <script> element, so the code itself must never close it.
  return result.outputFiles[0].text.trim().replace(/<\/(script)/gi, '<\\/$1');
}

export const moduleSource = (bundle) =>
  `// Generated by scripts/buildMcpTabBoard.mjs from src/lib/mcp/apps/tabBoard — do not edit.\n` +
  `export const TAB_BOARD_JS = ${JSON.stringify(bundle)};\n`;

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const source = moduleSource(await bundleTabBoard());
  await fs.mkdir(dirname(OUTPUT_PATH), { recursive: true });
  await fs.writeFile(OUTPUT_PATH, source);
  console.log(`buildMcpTabBoard: ${(source.length / 1024).toFixed(1)} KB → ${OUTPUT_PATH}`);
}
